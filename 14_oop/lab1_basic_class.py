class Kutra:
    pass


k1 = Kutra()
k2 = Kutra()

print("k1:", k1)
print("k2:", k2)

k1.naav = "मोती"
k1.vay = 3
k2.naav = "टॉमी"
k2.vay = 5

print(f"\n{k1.naav} - वय: {k1.vay}")
print(f"{k2.naav} - वय: {k2.vay}")


