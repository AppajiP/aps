"""
लॅब २ — पायथनमधील माहिती-प्रकार (Data Types)
=============================================
"""

vay = 15
print("integer:", vay)

unchi = 5.6
print("float:", unchi)

naav = "सीता"
print("string:", naav)

ahe_pass = True
nahi_fail = False
print("boolean:", ahe_pass, nahi_fail)

mitra_yadi = ["राम", "श्याम", "गणेश"]
print("list:", mitra_yadi)

guna = (90, 85, 95)
print("tuple:", guna)

vidyarthi = {"naav": "अर्जुन", "vay": 15}
print("dictionary:", vidyarthi)

ekach_phal = {"आंबा", "केळी", "सफरचंद"}
print("set:", ekach_phal)

kahich_nahi = None
print("None:", kahich_nahi)


