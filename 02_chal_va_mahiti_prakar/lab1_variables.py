"""
लॅब १ — चल (Variables) तयार करणे
==================================
"""

naav = "अर्जुन"
vay = 15
unchi = 5.6
ahe_vidyarthi = True

print("नाव:", naav)
print("वय:", vay)
print("उंची:", unchi)
print("विद्यार्थी आहे का?", ahe_vidyarthi)

vay = 16
print("नवीन वय:", vay)

a = 10
b = 20
c = a + b
print("बेरीज:", c)


"""
========================================================
प्रत्येक शब्दाचे स्पष्टीकरण:
========================================================

naav, vay, unchi  ->  चलांची नावे (variable names)
                      ती आपण ठेवली आहेत.

=                 ->  'assignment operator'
                      याचा अर्थ "उजवीकडची किंमत डावीकडच्या चलाला दे"
                      हे गणितातील समानता नाही!

"अर्जुन"           ->  string किंमत
15                 ->  integer किंमत
5.6                ->  float किंमत
True               ->  boolean किंमत (T मोठा हवा!)

vay = 16          ->  जुनी किंमत बदलून नवीन देणे.
                      चलात नवीन किंमत साठवली जाते.

c = a + b         ->  a व b ची बेरीज c मध्ये साठवली.
"""
