"""
लॅब ३ — Append mode (जोडणे)
==============================
"""

f = open("dairy.txt", "w", encoding="utf-8")
f.write("दिवस १: आज पायथन सुरू केले.\n")
f.close()

f = open("dairy.txt", "a", encoding="utf-8")
f.write("दिवस २: फंक्शन्स शिकलो.\n")
f.write("दिवस ३: फाइल हाताळणी शिकलो.\n")
f.close()

f = open("dairy.txt", "r", encoding="utf-8")
print(f.read())
f.close()


