"""
लॅब १ — फाइलमध्ये लिहिणे
==========================
"""

f = open("namaste.txt", "w", encoding="utf-8")
f.write("नमस्कार जग!\n")
f.write("मी पायथन शिकत आहे.\n")
f.write("फाइल हाताळणी मजेशीर आहे.\n")
f.close()

print("namaste.txt फाइलमध्ये लिहिले गेले!")

oli = [
    "१. आंबा\n",
    "२. केळी\n",
    "३. सफरचंद\n",
    "४. द्राक्ष\n"
]
f = open("phale.txt", "w", encoding="utf-8")
f.writelines(oli)
f.close()

print("phale.txt फाइलमध्ये यादी लिहिली!")


"""
========================================================
स्पष्टीकरण:
========================================================

open(filename, mode, encoding):
   - filename:  फाइलचे नाव (नसली तर तयार होते)
   - mode "w":  लिहिण्यासाठी (जुनी मिटते!)
   - encoding="utf-8":  मराठी अक्षरांसाठी आवश्यक

f.write(text):
   - text फाइलमध्ये लिहिते.
   - शेवटी \n टाकले नाही तर पुढची write त्याच ओळीवर येते!

f.writelines(list):
   - list मधल्या प्रत्येक string फाइलमध्ये लिहिते.
   - automatic \n टाकत नाही — स्वतः टाकावे लागते.

f.close():
   - फाइल बंद करणे महत्त्वाचे.
   - नाहीतर माहिती कधीकधी disk वर पोहोचत नाही.
   - 'with' वापरले की आपोआप close होते (पुढच्या लॅबमध्ये).
"""
