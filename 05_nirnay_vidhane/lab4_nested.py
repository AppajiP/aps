"""
लॅब ४ — Nested if (एका आत दुसरे)
==================================
"""

vay = 20
bharatiya = True

if bharatiya:
    if vay >= 18:
        print("तू मतदान करू शकतोस")
    else:
        print("तू भारतीय आहेस पण वय कमी")
else:
    print("तू भारतीय नागरिक नाहीस")


sankhya = 12
if sankhya > 0:
    if sankhya % 2 == 0:
        print("धन सम संख्या")
    else:
        print("धन विषम संख्या")
elif sankhya < 0:
    print("ऋण संख्या")
else:
    print("शून्य")


