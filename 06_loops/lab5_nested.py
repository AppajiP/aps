"""
लॅब ५ — Nested लूप — पाढे
===========================
"""

print("===== २ ते ५ चे पाढे =====\n")

for n in range(2, 6):
    print(f"---- {n} चा पाढा ----")
    for i in range(1, 11):
        print(f"{n} x {i} = {n * i}")
    print()


