"""
लॅब १ — for लूप
=================
"""

print("१ ते ५:")
for i in range(1, 6):
    print(i)

print("\nफळांची यादी:")
phale = ["आंबा", "केळी", "सफरचंद", "द्राक्ष"]
for phal in phale:
    print(phal)

print("\nनावातील अक्षरे:")
naav = "पायथन"
for akshar in naav:
    print(akshar)


