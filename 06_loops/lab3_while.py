"""
लॅब ३ — while लूप
==================
"""

i = 1
while i <= 5:
    print("क्रमांक:", i)
    i += 1

print()

berij = 0
n = 1
while n <= 10:
    berij += n
    n += 1
print("१ ते १० ची बेरीज:", berij)

print()
sankhya = 12345
ulta = 0
while sankhya > 0:
    ank = sankhya % 10
    ulta = ulta * 10 + ank
    sankhya = sankhya // 10
print("उलटी संख्या:", ulta)


