phale = ["आंबा", "केळी", "सफरचंद", "द्राक्ष"]

print("आंबा यादीत आहे का?:", "आंबा" in phale)
print("पेरू यादीत आहे का?:", "पेरू" in phale)
print("पेरू यादीत नाही का?:", "पेरू" not in phale)

vakya = "मला पायथन आवडते"
print("'पायथन' वाक्यात आहे का?:", "पायथन" in vakya)

a = None
b = None
print("a is None :", a is None)
print("a is b    :", a is b)

c = 100
d = 100
print("c is d    :", c is d)


