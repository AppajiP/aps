"""
लॅब ४ — नियुक्ती ऑपरेटर्स (Assignment)
========================================
"""

x = 10
print("सुरुवात:", x)

x += 5
print("x += 5 नंतर:", x)

x -= 3
print("x -= 3 नंतर:", x)

x *= 2
print("x *= 2 नंतर:", x)

x /= 4
print("x /= 4 नंतर:", x)

x **= 2
print("x **= 2 नंतर:", x)

x //= 3
print("x //= 3 नंतर:", x)

x %= 4
print("x %= 4 नंतर:", x)


