a = 17
b = 5

print("बेरीज (a + b)        =", a + b)
print("वजाबाकी (a - b)      =", a - b)
print("गुणाकार (a * b)      =", a * b)
print("भागाकार (a / b)      =", a / b)
print("पूर्णांक भागाकार a//b =", a // b)
print("शिल्लक (a % b)       =", a % b)
print("घात (a ** b)         =", a ** b)


