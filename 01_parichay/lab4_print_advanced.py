"""
लॅब ४ — print() चे प्रगत उपयोग (sep व end)
============================================
"""

print("राम", "श्याम", "गणेश", sep=", ")

print("मुंबई", "पुणे", "नागपूर", sep=" -> ")

print("दिनांक:", 17, 5, 2026, sep="/")

print("ओळ १", end=" ")
print("ओळ २")

print("क्रमांक:", end=" ")
print(100)

print("***", end="")
print("***", end="")
print("***")


"""
========================================================
स्पष्टीकरण:
========================================================

sep  ->  'separator' चे लघुरूप.
         अनेक गोष्टी एकत्र छापताना त्यांच्या मधे काय यावे ते ठरवते.
         डीफॉल्ट: ' ' (एक space)

end  ->  print() संपल्यावर शेवटी काय यावे.
         डीफॉल्ट: '\n' (नवीन ओळ)
         म्हणून print() ने आपोआप नवीन ओळीवर output येते.

उदाहरण:
    print("क्रमांक:", end=" ")
    print(100)
    --> output:  क्रमांक: 100

जर end="" लिहिले तर पुढचे print() त्याच ओळीवर येते.
"""
