phale = ["आंबा", "केळी", "सफरचंद", "द्राक्ष"]
print("फळांची यादी:", phale)
print("एकूण फळे:", len(phale))

guna = [85, 92, 78, 65, 90]
print("\nगुण:", guna)
print("एकूण:", sum(guna))
print("सर्वात जास्त:", max(guna))
print("सर्वात कमी:", min(guna))

rikami = []
print("\nरिकामी यादी:", rikami, "लांबी:", len(rikami))

mishra = ["राम", 15, 5.6, True, [1, 2, 3]]
print("\nमिश्र यादी:", mishra)


