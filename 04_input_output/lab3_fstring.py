"""
लॅब ३ — f-strings (Formatted Strings)
=======================================
"""

naav = "अर्जुन"
vay = 15
unchi = 5.67

print(f"माझे नाव {naav} आहे.")
print(f"माझे वय {vay} आहे.")
print(f"पुढच्या वर्षी मी {vay + 1} वर्षांचा होईन.")

print(f"माझी उंची {unchi:.2f} फूट आहे.")
print(f"माझी उंची {unchi:.4f} फूट आहे.")

a = 7
b = 3
print(f"{a} + {b} = {a + b}")
print(f"{a} * {b} = {a * b}")
print(f"{a} / {b} = {a / b:.2f}")


