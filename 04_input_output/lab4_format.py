"""
लॅब ४ — .format() आणि % पद्धत
===============================
"""

naav = "सीता"
vay = 14

print("नाव: {} | वय: {}".format(naav, vay))

print("{1} ही {0} वर्षांची आहे.".format(vay, naav))

print("{n} ही {v} वर्षांची आहे.".format(n=naav, v=vay))

print("नाव: %s | वय: %d" % (naav, vay))
print("टक्केवारी: %.2f%%" % 87.5)


"""
========================================================
स्पष्टीकरण:
========================================================

.format() पद्धत:
   "{}".format(x)        ->  क्रमानुसार बसवते
   "{0} {1}".format(a,b) ->  index नुसार
   "{n}".format(n=...)   ->  नावानुसार

% पद्धत (जुनी, पण उपयोगी):
   %s -> string
   %d -> integer
   %f -> float
   %.2f -> २ दशांश float
   %% -> टक्के चिन्ह (%) छापायला

टीप:
   आधुनिक कोडमध्ये f-strings वापरा.
   जुने कोड वाचताना .format() आणि % कळायला हवे.
"""
