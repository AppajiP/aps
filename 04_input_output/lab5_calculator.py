print("===== साधा कॅल्क्युलेटर =====")

a = float(input("पहिली संख्या: "))
b = float(input("दुसरी संख्या: "))

print(f"\n{a} + {b} = {a + b}")
print(f"{a} - {b} = {a - b}")
print(f"{a} * {b} = {a * b}")
if b != 0:
    print(f"{a} / {b} = {a / b:.2f}")
else:
    print("भागाकार शक्य नाही (शून्याने भाग)")


