PI = 3.14159


def berij(a, b):
    return a + b


def vajabaki(a, b):
    return a - b


def gunakar(a, b):
    return a * b


def varg(n):
    return n * n


def varta_kshetraphal(trijya):
    return PI * trijya * trijya
