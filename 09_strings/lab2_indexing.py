"""
लॅब २ — String Indexing व Slicing
====================================
"""

s = "पायथन"

print("लांबी:", len(s))
print("s[0] =", s[0])
print("s[1] =", s[1])
print("s[-1] =", s[-1])

print("\n--- Slicing ---")
print("s[1:4]   =", s[1:4])
print("s[:3]    =", s[:3])
print("s[2:]    =", s[2:])
print("s[::-1]  =", s[::-1])

vakya = "मला पायथन आवडते"
print("\nपहिले ३ अक्षरे:", vakya[:3])
print("शेवटी ५ अक्षरे:", vakya[-5:])

print("\nलूप:")
for c in "अबकड":
    print(c)


